-- =========================================================
-- craft_results テーブル
-- 調合計算結果(2〜100)から、対応する完成アイテムを引くための対応表。
-- 0, 1, 101以上は特殊値としてService側(AlchemyService)でハードコードして処理する想定。
-- =========================================================

CREATE TABLE IF NOT EXISTS craft_results (
    id BIGINT NOT NULL AUTO_INCREMENT,
    calculated_value INT NOT NULL COMMENT '調合計算結果の値(2〜100)',
    item_id BIGINT NOT NULL COMMENT '対応するアイテムのID',
    PRIMARY KEY (id),
    UNIQUE KEY uk_calculated_value (calculated_value)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='調合計算結果(value)からアイテムを引く対応表';

